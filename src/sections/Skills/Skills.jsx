import { useEffect, useRef, useState } from "react";
import styles from "./SkillsStyles.module.css";
import checkMarkIconDark from "../../assets/checkmark-dark.svg";
import checkMarkIconLight from "../../assets/checkmark-light.svg";
import SkillList from "../../common/SkillList";
import { useTheme } from "../../common/ThemeContex";

const skillsData = [
  "HTML",
  "CSS",
  "JavaScript",
  "React",
  "Redux.js",
  "Creative Suite",
  "UI/UX",
  "Figma",
  "SEO",
  "WordPress",
  "Divi Theme",
  "MongoDB",
  "Bootstrap",
  "GitHub",
];

function Skills() {
  const { theme } = useTheme();
  const checkMarkIcon =
    theme === "light" ? checkMarkIconLight : checkMarkIconDark;

  const trackRef = useRef(null);
  const scrollState = useRef({ isInteracting: false, resumeTimeout: null });
  const scrollPos = useRef(0);
  const dragRef = useRef({ isDown: false, startX: 0, scrollLeft: 0 });
  const [isGrabbing, setIsGrabbing] = useState(false);

  useEffect(() => {
    const track = trackRef.current;
    if (!track) return;

    let animationFrameId;

    const scroll = () => {
      if (!scrollState.current.isInteracting && !dragRef.current.isDown) {
        scrollPos.current += 0.5; // Scroll speed

        if (scrollPos.current >= track.scrollWidth / 2) {
          scrollPos.current = 0;
        } else if (scrollPos.current < 0) {
          scrollPos.current = track.scrollWidth / 2;
        }
        
        track.scrollLeft = scrollPos.current;
      }
      animationFrameId = requestAnimationFrame(scroll);
    };

    animationFrameId = requestAnimationFrame(scroll);

    return () => cancelAnimationFrame(animationFrameId);
  }, []);

  const handleUserInteraction = () => {
    scrollState.current.isInteracting = true;
    clearTimeout(scrollState.current.resumeTimeout);

    scrollState.current.resumeTimeout = setTimeout(() => {
      scrollState.current.isInteracting = false;
      if (trackRef.current) {
        scrollPos.current = trackRef.current.scrollLeft;
      }
    }, 5000); // 5 seconds of inactivity
  };

  const handleScroll = () => {
    // Ignore scroll events generated by the auto-scroll script itself
    if (!scrollState.current.isInteracting && !dragRef.current.isDown) return;

    const track = trackRef.current;
    if (!track) return;

    // Wrap around for infinite scrolling
    const halfWidth = track.scrollWidth / 2;
    if (halfWidth > 0) {
      if (track.scrollLeft >= halfWidth) {
        track.scrollLeft -= halfWidth;
        scrollPos.current = track.scrollLeft;
      } else if (track.scrollLeft <= 0) {
        track.scrollLeft += halfWidth;
        scrollPos.current = track.scrollLeft;
      } else {
        scrollPos.current = track.scrollLeft;
      }
    }
  };

  // Mouse drag-to-scroll handlers
  const handleMouseDown = (e) => {
    const track = trackRef.current;
    if (!track) return;

    dragRef.current.isDown = true;
    dragRef.current.startX = e.pageX - track.offsetLeft;
    dragRef.current.scrollLeft = track.scrollLeft;
    setIsGrabbing(true);
    handleUserInteraction();
  };

  const handleMouseMove = (e) => {
    if (!dragRef.current.isDown) return;
    e.preventDefault();

    const track = trackRef.current;
    if (!track) return;

    const x = e.pageX - track.offsetLeft;
    const walk = x - dragRef.current.startX;
    track.scrollLeft = dragRef.current.scrollLeft - walk;
    scrollPos.current = track.scrollLeft;
    handleScroll();
  };

  const handleMouseUpOrLeave = () => {
    if (dragRef.current.isDown) {
      dragRef.current.isDown = false;
      setIsGrabbing(false);
      handleUserInteraction();
    }
  };

  return (
    <div id="skills" className={styles.container}>
      <div 
        className={`${styles.marqueeWrapper} ${isGrabbing ? styles.isGrabbing : ""}`} 
        ref={trackRef}
        onScroll={handleScroll}
        onWheel={handleUserInteraction}
        onTouchStart={handleUserInteraction}
        onTouchMove={handleUserInteraction}
        onMouseDown={handleMouseDown}
        onMouseMove={handleMouseMove}
        onMouseUp={handleMouseUpOrLeave}
        onMouseLeave={handleMouseUpOrLeave}
        onKeyDown={handleUserInteraction}
      >
        <div className={styles.marqueeTrack}>
          <div className={styles.skillGroup}>
            {skillsData.map((skill) => (
              <SkillList key={skill} src={checkMarkIcon} skill={skill} />
            ))}
          </div>
          <div className={styles.skillGroup}>
            {skillsData.map((skill) => (
              <SkillList
                key={"dup-" + skill}
                src={checkMarkIcon}
                skill={skill}
              />
            ))}
          </div>
        </div>
      </div>
    </div>
  );
}

export default Skills;
